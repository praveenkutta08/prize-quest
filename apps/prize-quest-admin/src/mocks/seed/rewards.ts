/** Category catalog with counts computed from the reward seed. */
export function buildCategoryInfo(rewards: RewardItem[]): RewardCategoryInfo[] {
  return (Object.keys(CATEGORY_LABEL) as RewardCategory[]).map((key) => ({
    key,
    label: CATEGORY_LABEL[key],
    count: rewards.filter((r) => r.category === key).length,
  }));
}

/** Fresh clones so the mutable DB never aliases the seed arrays. */
export function seedRewards(): RewardItem[] {
  return REWARDS.map((r) => structuredClone(r));
}
export function seedVendors(): Vendor[] {
  return VENDORS.map((v) => structuredClone(v));
}
