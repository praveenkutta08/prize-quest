/** Build a reward, deriving `marginPct` and `inStock` the way MSW does. */
function reward(
  r: Omit<RewardItem, "marginPct" | "inStock"> & { marginPct?: number; inStock?: boolean },
): RewardItem {
  return {
    ...r,
    marginPct: deriveMargin(r.value, r.cost),
    inStock: r.stockCount > 0,
  };
}

